"""
Approval / registration / compliance catalogue with deterministic applicability rules.

PROVENANCE DISCIPLINE (spec §52, §58)
-------------------------------------
Nothing in this file asserts a legal conclusion about a specific user's project.
Each entry records:
  * the statute or delegated legislation it is derived from (`legal_basis`),
  * the authority that administers it (`authority`),
  * the official portal where the user must actually apply (`official_portal_*`),
  * a `verification_status` that defaults to REQUIRES_VERIFICATION, because
    thresholds, fee slabs, forms and delegated powers change frequently and are
    frequently state-specific.

The rule engine evaluates `rule` against the project profile. A rule that
matches produces Applicability.APPLIES **for planning purposes**; the UI always
pairs it with the statute text and a "confirm with the authority" action. A rule
that does not match produces NOT_APPLICABLE, and where the profile is missing the
facts a rule needs, the engine produces UNKNOWN — never a guess.

`rule` grammar (evaluated by app/ai/rule_engine.py, no eval of arbitrary code):
    and / or / not, parentheses, comparisons (== != > >= < <=), `in`, `not in`
    profile field names, literals, and the helpers:
      has(field)          field is present and non-empty
      num(field, default) numeric coercion
      truthy(field)       true-ish value
      anyof(field, [...])  list field shares at least one member
      state_in([...])      project state matches one of the codes
      industry_in([...])   project industry code matches one of the codes
"""
