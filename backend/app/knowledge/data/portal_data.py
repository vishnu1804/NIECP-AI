"""
Government portal directory (spec §17).

These are the official national portals that industrial applicants in India are
directed to. They are stored with a verification status and a
`last_verified_at` timestamp so the UI can always show *when* the link was last
checked rather than implying permanent accuracy. `integration_status` is
NOT_CONNECTED by default: NIECP-AI opens the official portal for the user, it
does not impersonate it (spec §52).
"""
from __future__ import annotations

from typing import Any

P = "PENDING_VERIFICATION"


def P_(  # noqa: N802
    name: str,
    department: str,
    url: str,
    level: str = "CENTRAL",
    *,
    short_name: str | None = None,
    ministry: str | None = None,
    service: str | None = None,
    services: list[str] | None = None,
    description: str | None = None,
    categories: list[str] | None = None,
    keywords: list[str] | None = None,
    state_code: str | None = None,
    verification_status: str = "REQUIRES_VERIFICATION",
) -> dict[str, Any]:
    return {
        "name": name,
        "short_name": short_name,
        "department": department,
        "ministry": ministry,
        "official_url": url,
        "level": level,
        "state_code": state_code,
        "service": service,
        "services_supported": services or [],
        "description": description,
        "categories": categories or [],
        "keywords": keywords or [],
        "integration_status": "NOT_CONNECTED",
        "verification_status": verification_status,
    }


