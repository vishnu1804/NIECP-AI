def question_sets_from_description(description: str, base: list[str] | None = None) -> list[str]:
    """Derive relevant question sets from free text (the 'Other' industry path)."""
    text = (description or "").lower()
    sets: list[str] = list(base or ["operations", "water", "air", "waste", "fire", "electrical", "labour"])
    for keywords, qset in KEYWORD_QUESTION_MAP:
        if any(k in text for k in keywords) and qset not in sets:
            sets.append(qset)
    return sets


