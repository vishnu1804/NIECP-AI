"""
Government schemes & incentives catalogue (spec §18, §19).

Every scheme records:
  * the administering authority and the official URL,
  * `eligibility` as machine-evaluable expressions AND human-readable text,
  * a `verification_status` of REQUIRES_VERIFICATION with a note, because
    scheme guidelines, budgetary allocations and application windows change
    frequently and some schemes close to new applications at short notice.

NIECP-AI never states that a user IS eligible. The Scheme Agent reports which
documented criteria are met, which are not met, and which cannot be evaluated
because the profile lacks the information (spec §18: "Do not claim eligibility
unless the documented criteria and user information support it").
"""
from __future__ import annotations

from typing import Any


def S(  # noqa: N802
    code: str,
    name: str,
    authority: str,
    level: str,
    categories: list[str],
    short: str,
    benefits: list[str],
    criteria: list[tuple[str, str, str]],
    *,
    ministry: str | None = None,
    state_code: str | None = None,
    description: str | None = None,
    documents: list[str] | None = None,
    process: str | None = None,
    url: str | None = None,
    source_name: str | None = None,
    application_mode: str | None = None,
    eligibility_summary: str | None = None,
) -> dict[str, Any]:
    """criteria entries are (criterion_key, expression, human_text)."""
    return {
        "code": code,
        "name": name,
        "authority": authority,
        "ministry": ministry,
        "level": level,
        "state_code": state_code,
        "categories": categories,
        "short_description": short,
        "description": description or short,
        "benefits": benefits,
        "eligibility_criteria": [
            {"criterion_key": k, "expression": e, "human_text": h} for k, e, h in criteria
        ],
        "eligibility_summary": eligibility_summary
        or "Eligibility is assessed against the criteria published by the administering authority. NIECP-AI shows which criteria your project data satisfies and which it cannot evaluate.",
        "required_documents": documents or [],
        "application_process": process,
        "application_mode": application_mode,
        "official_url": url,
        "official_source_name": source_name,
        "verification_status": "REQUIRES_VERIFICATION",
        "confidence": "REQUIRES_VERIFICATION",
    }


